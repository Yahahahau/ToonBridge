# Feature census of an extracted XFL folder (counts per feature). Usage: python3 -I census.py <xfl dir> [...]
import sys,os,re,glob,collections
def census(root):
    C=collections.Counter()
    files=[os.path.join(root,'DOMDocument.xml')]+glob.glob(os.path.join(root,'LIBRARY','**','*.xml'),recursive=True)
    for f in files:
        t=open(f,encoding='utf-8',errors='replace').read()
        for tag in ['DOMShape','DOMGroup','DOMSymbolInstance','DOMBitmapInstance','DOMStaticText','DOMDynamicText','DOMInputText','DOMTLFText','DOMVideoInstance','DOMRectangleObject','DOMOvalObject','DOMComponentInstance','LinearGradient','RadialGradient','BitmapFill','SolidStroke','DashedStroke','DottedStroke','RaggedStroke','StippleStroke','HatchedStroke','VariablePointWidth','CustomEase','DOMFrame','DOMLayer','DOMTimeline','BlurFilter','DropShadowFilter','GlowFilter','BevelFilter','AdjustColorFilter','GradientGlowFilter','GradientBevelFilter','motionObjectXML','AnimationCore']:
            C[tag]+=len(re.findall(r'<'+tag+r'[\s>/]',t))
        C['layer:mask']+=len(re.findall(r'<DOMLayer[^>]*layerType="mask"',t))
        C['layer:guide']+=len(re.findall(r'<DOMLayer[^>]*layerType="guide"',t))
        C['layer:folder']+=len(re.findall(r'<DOMLayer[^>]*layerType="folder"',t))
        C['layer:masked(parentLayerIndex)']+=len(re.findall(r'<DOMLayer[^>]*parentLayerIndex=',t))
        C['layer:hidden']+=len(re.findall(r'<DOMLayer[^>]*visible="false"',t))
        C['layer:locked']+=len(re.findall(r'<DOMLayer[^>]*locked="true"',t))
        C['layer:outline']+=len(re.findall(r'<DOMLayer[^>]*outline="true"',t))
        C['frame:label(name)']+=len(re.findall(r'<DOMFrame[^>]*\sname="',t))
        C['frame:sound']+=len(re.findall(r'<DOMFrame[^>]*soundName=',t))
        C['frame:script']+=len(re.findall(r'<Actionscript',t))
        C['frame:tween motion']+=len(re.findall(r'tweenType="motion"',t))
        C['frame:tween shape']+=len(re.findall(r'tweenType="shape"',t))
        C['frame:tween motion object']+=len(re.findall(r'tweenType="motion object"',t))
        C['frame:blank keyframe']+=len(re.findall(r'<DOMFrame[^>]*/>',t))+len(re.findall(r'<elements/>',t))
        C['frame:duration0']+=len(re.findall(r'duration="0"',t))
        C['inst:graphic']+=len(re.findall(r'symbolType="graphic"',t))
        C['inst:button']+=len(re.findall(r'<DOMSymbolInstance[^>]*symbolType="button"',t))
        C['inst:loop play once']+=len(re.findall(r'loop="play once"',t))
        C['inst:loop single frame']+=len(re.findall(r'loop="single frame"',t))
        C['inst:loop reverse']+=len(re.findall(r'loop="(?:play once reverse|loop reverse)"',t))
        C['inst:firstFrame']+=len(re.findall(r'firstFrame="',t))
        C['inst:lastFrame']+=len(re.findall(r'lastFrame="',t))
        C['inst:blendMode']+=len(re.findall(r'blendMode="',t))
        C['inst:color tint']+=len(re.findall(r'tintMultiplier="',t))
        C['inst:color alpha']+=len(re.findall(r'alphaMultiplier="',t))
        C['inst:color advanced']+=len(re.findall(r'(?:red|green|blue)Offset="',t))
        C['inst:color brightness']+=len(re.findall(r'brightness="',t))
        C['inst:3D']+=len(re.findall(r'centerPoint3D|Matrix3D|rotationX=',t))
        C['inst:cacheAsBitmap']+=len(re.findall(r'cacheAsBitmap="true"',t))
        C['inst:visible=false']+=len(re.findall(r'<DOMSymbolInstance[^>]*isVisible="false"',t))
        C['ease:acceleration!=0']+=len(re.findall(r'acceleration="-?[1-9]',t))
        C['tween:rotate cw/ccw']+=len(re.findall(r'motionTweenRotate="(?:clockwise|counter-clockwise)"',t))
        C['tween:scale off']+=len(re.findall(r'motionTweenScale="false"',t))
        C['tween:orientToPath']+=len(re.findall(r'motionTweenOrientToPath="true"',t))
        C['tween:sync']+=len(re.findall(r'motionTweenSync="true"',t))
        C['shape:hint']+=len(re.findall(r'<ShapeHint|shapeHints',t))
    d=open(files[0],encoding='utf-8',errors='replace').read()
    C['doc:scenes']=len(re.findall(r'<DOMTimeline[\s>]',d.split('<timelines>')[1] if '<timelines>' in d else ''))
    C['doc:media items']=len(re.findall(r'<DOM(?:Bitmap|Sound|Video)Item',d))
    C['doc:fonts']=len(re.findall(r'<DOMFontItem',d))
    C['doc:library symbols']=len(re.findall(r'<Include ',d))
    return C
roots=sys.argv[1:]
cs=[census(r) for r in roots]
keys=sorted(set().union(*cs))
print('feature\t'+'\t'.join(os.path.basename(r.rstrip('/')) for r in roots))
for k in keys:
    if any(c[k] for c in cs): print(k+'\t'+'\t'.join(str(c[k]) for c in cs))
